const Glyphs = [_][]const u8{ " ", "▘", "▝", "▀", "▖", "▌", "▞", "▛", "▗", "▚", "▐", "▜", "▄", "▙", "▟", "█" };

pub const width = Cells[0].len / 3;
pub const height = Cells.len;

pub fn writeLine(writer: anytype, line: usize, use_color: bool) !void {
    var foreground: u8 = 0;
    var background: u8 = 0;
    if (use_color) try writer.writeAll("\x1b[0m");

    const cells = Cells[line];
    for (0..width) |column| {
        const offset = column * 3;
        const fg = colorIndex(cells[offset]);
        const bg = colorIndex(cells[offset + 1]);
        const mask = colorIndex(cells[offset + 2]);
        if (!use_color) {
            try writer.writeAll(monochromeGlyph(fg, bg, mask));
            continue;
        }

        if (foreground != fg) {
            try writeColor(writer, fg, true);
            foreground = fg;
        }
        if (background != bg) {
            try writeColor(writer, bg, false);
            background = bg;
        }
        try writer.writeAll(Glyphs[mask]);
    }

    if (use_color) try writer.writeAll("\x1b[0m");
}

fn colorIndex(digit: u8) u8 {
    return if (digit <= '9') digit - '0' else digit - 'a' + 10;
}

fn writeColor(writer: anytype, index: u8, foreground: bool) !void {
    if (index == 0) {
        try writer.writeAll(if (foreground) "\x1b[39m" else "\x1b[49m");
        return;
    }
    const rgb = Palette[index];
    try writer.print("\x1b[{};2;{};{};{}m", .{ @as(u8, if (foreground) 38 else 48), rgb[0], rgb[1], rgb[2] });
}

fn monochromeGlyph(foreground: u8, background: u8, mask: u8) []const u8 {
    if (background == 0 and mask != 15) return Glyphs[mask];
    const fg = Palette[foreground];
    const bg = Palette[background];
    const foreground_pixels: u16 = @popCount(mask);
    const fg_sum = @as(u16, fg[0]) + fg[1] + fg[2];
    const bg_sum = @as(u16, bg[0]) + bg[1] + bg[2];
    const brightness = (fg_sum * foreground_pixels + bg_sum * (4 - foreground_pixels)) / 12;
    if (brightness >= 220) return "░";
    if (brightness >= 160) return "▒";
    if (brightness >= 100) return "▓";
    return "█";
}
